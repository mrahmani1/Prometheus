#!/usr/bin/env python3
"""
Update all HTML modules to include comprehensive volcano selector navigation
"""
import os
import re

def update_volcano_navigation(filename):
    """Update volcano navigation in HTML file"""
    if not os.path.exists(filename):
        print(f"[WARNING] File not found: {filename}")
        return False
    
    try:
        with open(filename, 'r', encoding='utf-8') as f:
            content = f.read()
        
        # Check if file contains volcano-related content
        volcano_indicators = [
            'volcano', 'volcanic', 'eruption', 'magma', 'lava', 'crater',
            'HOLOCENE_VOLCANOES', 'volcano-selector', 'selectVolcano'
        ]
        
        has_volcano_content = any(indicator.lower() in content.lower() for indicator in volcano_indicators)
        
        if not has_volcano_content:
            print(f"[SKIP] No volcano content detected: {filename}")
            return False
        
        # Look for existing volcano selectors and replace with comprehensive version
        replacements_made = False
        
        # Replace old volcano selector dropdowns
        old_selectors = [
            r'<select[^>]*id=["\']volcano[^"\']*["\'][^>]*>.*?</select>',
            r'<select[^>]*class=["\'][^"\']*volcano[^"\']*["\'][^>]*>.*?</select>',
            r'<div[^>]*class=["\'][^"\']*volcano-selector[^"\']*["\'][^>]*>.*?</div>',
            r'<div[^>]*id=["\']volcano-selector[^"\']*["\'][^>]*>.*?</div>'
        ]
        
        for pattern in old_selectors:
            if re.search(pattern, content, re.IGNORECASE | re.DOTALL):
                content = re.sub(pattern, 
                    '<!-- Volcano selector will be auto-generated by comprehensive_volcano_selector.js -->\n    <div id="auto-volcano-selector"></div>', 
                    content, flags=re.IGNORECASE | re.DOTALL)
                replacements_made = True
        
        # Add volcano selector integration if not present
        if 'comprehensive_volcano_selector.js' not in content and has_volcano_content:
            # Find a good insertion point for initialization
            init_code = '''
    <!-- Initialize comprehensive volcano selector -->
    <script>
        document.addEventListener('DOMContentLoaded', function() {
            // Wait for comprehensive volcano selector to load
            setTimeout(function() {
                if (window.initializeVolcanoSelector) {
                    // Remove any existing volcano selectors to avoid conflicts
                    const existingSelectors = document.querySelectorAll('.volcano-selector-panel');
                    existingSelectors.forEach(sel => sel.remove());
                    
                    // Initialize new comprehensive selector
                    window.initializeVolcanoSelector();
                    console.log('🌋 Comprehensive volcano selector integrated for this module');
                }
            }, 2000);
        });
    </script>'''
            
            # Insert before closing body tag
            if '</body>' in content:
                content = content.replace('</body>', init_code + '\n</body>')
                replacements_made = True
            elif '</html>' in content:
                content = content.replace('</html>', init_code + '\n</html>')
                replacements_made = True
        
        # Update existing volcano selector JavaScript code
        js_patterns = [
            (r'selectVolcano\s*\([^)]*\)', 'focusOnVolcano(volcanoName, volcanoInfo)'),
            (r'getElementById\(["\']volcano-select["\']\)', 'getElementById("volcano-select")'),
            (r'getElementById\(["\']volcanoSelect["\']\)', 'getElementById("volcano-select")')
        ]
        
        for old_pattern, new_pattern in js_patterns:
            if re.search(old_pattern, content):
                content = re.sub(old_pattern, new_pattern, content)
                replacements_made = True
        
        if replacements_made:
            with open(filename, 'w', encoding='utf-8') as f:
                f.write(content)
            print(f"[OK] Updated volcano navigation: {filename}")
            return True
        else:
            print(f"[SKIP] No volcano navigation updates needed: {filename}")
            return False
            
    except Exception as e:
        print(f"[ERROR] Failed to update {filename}: {e}")
        return False

# List of HTML files to update
html_files = [
    'advanced_insar_analysis.html',
    'advanced_tectonic_simulation.html',
    'earthquake_stress_visualization.html',
    'volcanic_system_simulator.html',
    'mantle_dynamics_simulator.html',
    'professional_tectonic_simulation.html',
    'scientific_tectonic_simulation.html',
    'volcano_magma_simulation.html',
    'ml_dashboard.html',
    'debug_dashboard.html',
    'gplates_advanced.html'
]

if __name__ == "__main__":
    updated_files = []
    
    print("Updating volcano navigation in all modules...")
    print("Integrating hierarchical Continent -> Country -> Volcanic System selector")
    
    for filename in html_files:
        if update_volcano_navigation(filename):
            updated_files.append(filename)
    
    print(f"\nSummary: Updated volcano navigation in {len(updated_files)} files")
    if updated_files:
        print("Files with updates:", ', '.join(updated_files))