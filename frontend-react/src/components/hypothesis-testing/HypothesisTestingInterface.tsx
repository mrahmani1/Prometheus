import React, { useState, useCallback, useEffect, useMemo } from 'react';
import { DndProvider, useDrag, useDrop } from 'react-dnd';
import { HTML5Backend } from 'react-dnd-html5-backend';
import { 
  Box, 
  Paper, 
  Typography, 
  Button, 
  Slider, 
  TextField, 
  Select, 
  MenuItem, 
  FormControl, 
  InputLabel,
  Chip,
  IconButton,
  Tooltip,
  Dialog,
  DialogTitle,
  DialogContent,
  DialogActions,
  Grid,
  Card,
  CardContent,
  LinearProgress,
  Alert,
  Tabs,
  Tab,
  Accordion,
  AccordionSummary,
  AccordionDetails
} from '@mui/material';
import {
  Add as AddIcon,
  Delete as DeleteIcon,
  Share as ShareIcon,
  Save as SaveIcon,
  PlayArrow as TestIcon,
  Compare as CompareIcon,
  History as HistoryIcon,
  AutoAwesome as AutoGenerateIcon,
  ExpandMore as ExpandMoreIcon,
  Science as ScienceIcon,
  TrendingUp as TrendingUpIcon,
  Assessment as AssessmentIcon
} from '@mui/icons-material';
import { 
  CausalHypothesis, 
  CausalVariable, 
  StatisticalTest, 
  HypothesisTestResult,
  GeologicalProcess,
  CausalEdge,
  TestParameters,
  HypothesisComparison,
  CollaborativeSession
} from '../../types/causal-analysis';
import { CausalGraphBuilder } from './CausalGraphBuilder';
import { StatisticalTestPanel } from './StatisticalTestPanel';
import { HypothesisComparator } from './HypothesisComparator';
import { CollaborativeReviewPanel } from './CollaborativeReviewPanel';
import { AutoHypothesisGenerator } from './AutoHypothesisGenerator';
import { HypothesisVersionControl } from './HypothesisVersionControl';

interface HypothesisTestingInterfaceProps {
  availableVariables: CausalVariable[];
  geologicalProcesses: GeologicalProcess[];
  onHypothesisTest: (hypothesis: CausalHypothesis, parameters: TestParameters) => Promise<HypothesisTestResult>;
  onHypothesisSave: (hypothesis: CausalHypothesis) => Promise<void>;
  onHypothesisShare: (hypothesis: CausalHypothesis, collaborators: string[]) => Promise<void>;
  collaborativeSession?: CollaborativeSession;
}

export const HypothesisTestingInterface: React.FC<HypothesisTestingInterfaceProps> = ({
  availableVariables,
  geologicalProcesses,
  onHypothesisTest,
  onHypothesisSave,
  onHypothesisShare,
  collaborativeSession
}) => {
  const [currentHypothesis, setCurrentHypothesis] = useState<CausalHypothesis | null>(null);
  const [testResults, setTestResults] = useState<HypothesisTestResult[]>([]);
  const [isTestingInProgress, setIsTestingInProgress] = useState(false);
  const [selectedTab, setSelectedTab] = useState(0);
  const [testParameters, setTestParameters] = useState<TestParameters>({
    significanceLevel: 0.05,
    bootstrapSamples: 1000,
    crossValidationFolds: 5,
    temporalLagRange: [0, 365], // days
    spatialScaleRange: [1, 1000], // km
    confidenceInterval: 0.95,
    robustnessTests: true,
    multipleTestingCorrection: 'bonferroni'
  });
  const [comparisonHypotheses, setComparisonHypotheses] = useState<CausalHypothesis[]>([]);
  const [showShareDialog, setShowShareDialog] = useState(false);
  const [shareCollaborators, setShareCollaborators] = useState<string[]>([]);
  const [autoGeneratedHypotheses, setAutoGeneratedHypotheses] = useState<CausalHypothesis[]>([]);

  // Real-time parameter adjustment with debounced testing
  const debouncedTest = useCallback(
    debounce(async (hypothesis: CausalHypothesis, params: TestParameters) => {
      if (hypothesis && hypothesis.edges.length > 0) {
        setIsTestingInProgress(true);
        try {
          const result = await onHypothesisTest(hypothesis, params);
          setTestResults(prev => [result, ...prev.slice(0, 9)]); // Keep last 10 results
        } catch (error) {
          console.error('Hypothesis testing failed:', error);
        } finally {
          setIsTestingInProgress(false);
        }
      }
    }, 500),
    [onHypothesisTest]
  );

  // Auto-test when hypothesis or parameters change
  useEffect(() => {
    if (currentHypothesis && testParameters) {
      debouncedTest(currentHypothesis, testParameters);
    }
  }, [currentHypothesis, testParameters, debouncedTest]);

  const handleHypothesisChange = useCallback((hypothesis: CausalHypothesis) => {
    setCurrentHypothesis(hypothesis);
  }, []);

  const handleParameterChange = useCallback((paramName: keyof TestParameters, value: any) => {
    setTestParameters(prev => ({
      ...prev,
      [paramName]: value
    }));
  }, []);

  const handleSaveHypothesis = useCallback(async () => {
    if (currentHypothesis) {
      await onHypothesisSave(currentHypothesis);
    }
  }, [currentHypothesis, onHypothesisSave]);

  const handleShareHypothesis = useCallback(async () => {
    if (currentHypothesis && shareCollaborators.length > 0) {
      await onHypothesisShare(currentHypothesis, shareCollaborators);
      setShowShareDialog(false);
      setShareCollaborators([]);
    }
  }, [currentHypothesis, shareCollaborators, onHypothesisShare]);

  const handleAddToComparison = useCallback((hypothesis: CausalHypothesis) => {
    setComparisonHypotheses(prev => {
      if (prev.find(h => h.id === hypothesis.id)) return prev;
      return [...prev, hypothesis];
    });
  }, []);

  const latestTestResult = testResults[0];
  const hasValidHypothesis = currentHypothesis && currentHypothesis.edges.length > 0;

  return (
    <DndProvider backend={HTML5Backend}>
      <Box sx={{ height: '100vh', display: 'flex', flexDirection: 'column' }}>
        {/* Header */}
        <Paper sx={{ p: 2, mb: 2 }}>
          <Box sx={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
            <Typography variant="h5" sx={{ display: 'flex', alignItems: 'center', gap: 1 }}>
              <ScienceIcon />
              Causal Hypothesis Testing Laboratory
            </Typography>
            <Box sx={{ display: 'flex', gap: 1 }}>
              <Tooltip title="Auto-generate hypotheses">
                <IconButton 
                  onClick={() => setSelectedTab(4)}
                  color="primary"
                >
                  <AutoGenerateIcon />
                </IconButton>
              </Tooltip>
              <Tooltip title="Compare hypotheses">
                <IconButton 
                  onClick={() => setSelectedTab(2)}
                  color="secondary"
                >
                  <CompareIcon />
                </IconButton>
              </Tooltip>
              <Tooltip title="Version history">
                <IconButton 
                  onClick={() => setSelectedTab(5)}
                  color="info"
                >
                  <HistoryIcon />
                </IconButton>
              </Tooltip>
              <Button
                variant="contained"
                startIcon={<SaveIcon />}
                onClick={handleSaveHypothesis}
                disabled={!hasValidHypothesis}
              >
                Save
              </Button>
              <Button
                variant="outlined"
                startIcon={<ShareIcon />}
                onClick={() => setShowShareDialog(true)}
                disabled={!hasValidHypothesis}
              >
                Share
              </Button>
            </Box>
          </Box>
        </Paper>

        {/* Main Content */}
        <Box sx={{ flex: 1, display: 'flex', gap: 2 }}>
          {/* Left Panel - Hypothesis Builder */}
          <Paper sx={{ width: '40%', p: 2, overflow: 'auto' }}>
            <Tabs value={selectedTab} onChange={(_, newValue) => setSelectedTab(newValue)}>
              <Tab label="Build" />
              <Tab label="Test" />
              <Tab label="Compare" />
              <Tab label="Collaborate" />
              <Tab label="Auto-Generate" />
              <Tab label="History" />
            </Tabs>

            {selectedTab === 0 && (
              <CausalGraphBuilder
                availableVariables={availableVariables}
                geologicalProcesses={geologicalProcesses}
                hypothesis={currentHypothesis}
                onHypothesisChange={handleHypothesisChange}
                collaborativeSession={collaborativeSession}
              />
            )}

            {selectedTab === 1 && (
              <StatisticalTestPanel
                hypothesis={currentHypothesis}
                testParameters={testParameters}
                onParameterChange={handleParameterChange}
                testResult={latestTestResult}
                isTestingInProgress={isTestingInProgress}
              />
            )}

            {selectedTab === 2 && (
              <HypothesisComparator
                hypotheses={comparisonHypotheses}
                onRemoveHypothesis={(id) => 
                  setComparisonHypotheses(prev => prev.filter(h => h.id !== id))
                }
                onSelectHypothesis={setCurrentHypothesis}
              />
            )}

            {selectedTab === 3 && (
              <CollaborativeReviewPanel
                hypothesis={currentHypothesis}
                collaborativeSession={collaborativeSession}
                onHypothesisChange={handleHypothesisChange}
              />
            )}

            {selectedTab === 4 && (
              <AutoHypothesisGenerator
                availableVariables={availableVariables}
                geologicalProcesses={geologicalProcesses}
                onHypothesesGenerated={setAutoGeneratedHypotheses}
                onSelectHypothesis={setCurrentHypothesis}
                generatedHypotheses={autoGeneratedHypotheses}
              />
            )}

            {selectedTab === 5 && (
              <HypothesisVersionControl
                currentHypothesis={currentHypothesis}
                onHypothesisRestore={setCurrentHypothesis}
              />
            )}
          </Paper>

          {/* Right Panel - Results and Visualization */}
          <Paper sx={{ flex: 1, p: 2, overflow: 'auto' }}>
            <Typography variant="h6" gutterBottom sx={{ display: 'flex', alignItems: 'center', gap: 1 }}>
              <AssessmentIcon />
              Real-time Test Results
              {isTestingInProgress && <LinearProgress sx={{ ml: 2, flex: 1 }} />}
            </Typography>

            {!hasValidHypothesis && (
              <Alert severity="info" sx={{ mb: 2 }}>
                Build a causal hypothesis using the graph builder to see real-time test results.
              </Alert>
            )}

            {latestTestResult && (
              <Grid container spacing={2}>
                {/* Statistical Significance */}
                <Grid item xs={12} md={6}>
                  <Card>
                    <CardContent>
                      <Typography variant="subtitle1" gutterBottom>
                        Statistical Significance
                      </Typography>
                      <Box sx={{ display: 'flex', alignItems: 'center', gap: 2 }}>
                        <Typography variant="h4" color={
                          latestTestResult.pValue < testParameters.significanceLevel ? 'success.main' : 'error.main'
                        }>
                          {latestTestResult.pValue.toFixed(4)}
                        </Typography>
                        <Chip 
                          label={latestTestResult.pValue < testParameters.significanceLevel ? 'Significant' : 'Not Significant'}
                          color={latestTestResult.pValue < testParameters.significanceLevel ? 'success' : 'error'}
                        />
                      </Box>
                      <Typography variant="body2" color="text.secondary">
                        α = {testParameters.significanceLevel}
                      </Typography>
                    </CardContent>
                  </Card>
                </Grid>

                {/* Effect Size */}
                <Grid item xs={12} md={6}>
                  <Card>
                    <CardContent>
                      <Typography variant="subtitle1" gutterBottom>
                        Effect Size (Cohen's d)
                      </Typography>
                      <Typography variant="h4" color="primary">
                        {latestTestResult.effectSize.toFixed(3)}
                      </Typography>
                      <Typography variant="body2" color="text.secondary">
                        {getEffectSizeInterpretation(latestTestResult.effectSize)}
                      </Typography>
                    </CardContent>
                  </Card>
                </Grid>

                {/* Confidence Interval */}
                <Grid item xs={12}>
                  <Card>
                    <CardContent>
                      <Typography variant="subtitle1" gutterBottom>
                        {(testParameters.confidenceInterval * 100).toFixed(0)}% Confidence Interval
                      </Typography>
                      <Box sx={{ display: 'flex', alignItems: 'center', gap: 2 }}>
                        <Typography variant="body1">
                          [{latestTestResult.confidenceInterval.lower.toFixed(3)}, {latestTestResult.confidenceInterval.upper.toFixed(3)}]
                        </Typography>
                        <Chip 
                          label={latestTestResult.confidenceInterval.lower > 0 ? 'Positive Effect' : 
                                latestTestResult.confidenceInterval.upper < 0 ? 'Negative Effect' : 'Uncertain'}
                          color={latestTestResult.confidenceInterval.lower > 0 ? 'success' : 
                                latestTestResult.confidenceInterval.upper < 0 ? 'warning' : 'default'}
                        />
                      </Box>
                    </CardContent>
                  </Card>
                </Grid>

                {/* Robustness Tests */}
                {latestTestResult.robustnessTests && (
                  <Grid item xs={12}>
                    <Accordion>
                      <AccordionSummary expandIcon={<ExpandMoreIcon />}>
                        <Typography variant="subtitle1">Robustness Analysis</Typography>
                      </AccordionSummary>
                      <AccordionDetails>
                        <Grid container spacing={2}>
                          <Grid item xs={6}>
                            <Typography variant="body2">Bootstrap Stability:</Typography>
                            <LinearProgress 
                              variant="determinate" 
                              value={latestTestResult.robustnessTests.bootstrapStability * 100}
                              sx={{ mt: 1 }}
                            />
                            <Typography variant="caption">
                              {(latestTestResult.robustnessTests.bootstrapStability * 100).toFixed(1)}%
                            </Typography>
                          </Grid>
                          <Grid item xs={6}>
                            <Typography variant="body2">Cross-validation Score:</Typography>
                            <LinearProgress 
                              variant="determinate" 
                              value={latestTestResult.robustnessTests.crossValidationScore * 100}
                              sx={{ mt: 1 }}
                            />
                            <Typography variant="caption">
                              {(latestTestResult.robustnessTests.crossValidationScore * 100).toFixed(1)}%
                            </Typography>
                          </Grid>
                        </Grid>
                      </AccordionDetails>
                    </Accordion>
                  </Grid>
                )}

                {/* Add to Comparison */}
                <Grid item xs={12}>
                  <Button
                    variant="outlined"
                    startIcon={<CompareIcon />}
                    onClick={() => currentHypothesis && handleAddToComparison(currentHypothesis)}
                    disabled={!currentHypothesis}
                  >
                    Add to Comparison
                  </Button>
                </Grid>
              </Grid>
            )}

            {/* Test History */}
            {testResults.length > 1 && (
              <Box sx={{ mt: 3 }}>
                <Typography variant="h6" gutterBottom>
                  Recent Test History
                </Typography>
                {testResults.slice(1, 6).map((result, index) => (
                  <Card key={index} sx={{ mb: 1 }}>
                    <CardContent sx={{ py: 1 }}>
                      <Box sx={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
                        <Typography variant="body2">
                          p = {result.pValue.toFixed(4)}, d = {result.effectSize.toFixed(3)}
                        </Typography>
                        <Typography variant="caption" color="text.secondary">
                          {new Date(result.timestamp).toLocaleTimeString()}
                        </Typography>
                      </Box>
                    </CardContent>
                  </Card>
                ))}
              </Box>
            )}
          </Paper>
        </Box>

        {/* Share Dialog */}
        <Dialog open={showShareDialog} onClose={() => setShowShareDialog(false)} maxWidth="sm" fullWidth>
          <DialogTitle>Share Hypothesis</DialogTitle>
          <DialogContent>
            <TextField
              fullWidth
              label="Collaborator Emails"
              placeholder="Enter email addresses separated by commas"
              multiline
              rows={3}
              value={shareCollaborators.join(', ')}
              onChange={(e) => setShareCollaborators(e.target.value.split(',').map(email => email.trim()))}
              sx={{ mt: 2 }}
            />
          </DialogContent>
          <DialogActions>
            <Button onClick={() => setShowShareDialog(false)}>Cancel</Button>
            <Button onClick={handleShareHypothesis} variant="contained">Share</Button>
          </DialogActions>
        </Dialog>
      </Box>
    </DndProvider>
  );
};

// Utility functions
function debounce<T extends (...args: any[]) => any>(func: T, wait: number): T {
  let timeout: NodeJS.Timeout;
  return ((...args: any[]) => {
    clearTimeout(timeout);
    timeout = setTimeout(() => func(...args), wait);
  }) as T;
}

function getEffectSizeInterpretation(effectSize: number): string {
  const abs = Math.abs(effectSize);
  if (abs < 0.2) return 'Negligible effect';
  if (abs < 0.5) return 'Small effect';
  if (abs < 0.8) return 'Medium effect';
  return 'Large effect';
}